#!/usr/bin/env python3
"""
Interactive setup wizard for SORAT per-user local configuration.

Writes gitignored config to: .sorat/user.config
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from typing import Optional


def _prompt_value(prompt: str, default: Optional[str] = None) -> str:
    label = f"{prompt} [{default}]" if default else prompt
    try:
        raw = input(f"{label}: ").strip()
    except EOFError:
        return default or ""
    return raw if raw else (default or "")


def _prompt_yes_no(prompt: str, default: bool = True) -> bool:
    suffix = "[Y/n]" if default else "[y/N]"
    while True:
        try:
            raw = input(f"{prompt} {suffix}: ").strip().lower()
        except EOFError:
            return default
        if not raw:
            return default
        if raw in {"y", "yes"}:
            return True
        if raw in {"n", "no"}:
            return False
        print("Please answer 'y' or 'n'.")


def _validate_existing_path(path_value: str, label: str, expect_file: bool, non_interactive: bool) -> str:
    value = path_value.strip()
    if not value:
        return ""

    p = Path(value).expanduser()
    exists_ok = p.is_file() if expect_file else p.is_dir()
    if exists_ok:
        return str(p)

    kind = "file" if expect_file else "directory"
    message = f"Warning: {label} {kind} does not exist: {p}"
    if non_interactive:
        raise ValueError(message)
    print(message)
    if _prompt_yes_no("Continue with this value anyway?", default=False):
        return str(p)
    return ""


def _groovy_literal(value: Optional[str]) -> str:
    if not value:
        return "null"
    escaped = value.replace("\\", "\\\\").replace("'", "\\'")
    return f"'{escaped}'"


def _build_config_text(values: dict[str, str], root_dir: Path) -> str:
     return f"""/*
 * Auto-generated by bin/sorat_setup.py
 * This file is local-only and gitignored.
 */

params {{
    outdir                = {_groovy_literal(values['outdir'])}
    slurm_account         = {_groovy_literal(values['slurm_account'])}

    // Preferred generic defaults for SAX model-family auto input generation.
    sax_data_root         = {_groovy_literal(values['sax_data_root'])}
    sax_data_split        = {_groovy_literal(values['sax_data_split'])}

    // Legacy aliases retained for compatibility.
    acdc_dir              = {_groovy_literal(values['sax_data_root'])}
    acdc_dataset          = {_groovy_literal(values['sax_data_split'])}

    singularity_cache_dir = {_groovy_literal(values['singularity_cache_dir'])}
    preprocess_cache_dir  = {_groovy_literal(values['preprocess_cache_dir'])}

    singularity_local_binds = {_groovy_literal(values['singularity_local_binds'])}
    singularity_slurm_binds = {_groovy_literal(values['singularity_slurm_binds'])}

    default_inputs {{
        // Preferred generic keys.
        sax               = {_groovy_literal(values['sax_samplesheet'])}
        atrial            = {_groovy_literal(values['atrial_samplesheet'])}

        // Legacy aliases retained for compatibility.
        acdc              = {_groovy_literal(values['sax_samplesheet'])}
        mbas              = {_groovy_literal(values['atrial_samplesheet'])}
    }}

    atrial_nnunet {{
        dataset_root      = {_groovy_literal(values['atrial_data_root'])}

        // Legacy alias retained for compatibility.
        mbas_root         = {_groovy_literal(values['atrial_data_root'])}
    }}
}}
"""


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Configure local SORAT user settings")
    parser.add_argument("--non-interactive", action="store_true", help="Do not prompt; use provided args/defaults")
    parser.add_argument("--force", action="store_true", help="Overwrite existing .sorat/user.config")
    parser.add_argument("--print-only", action="store_true", help="Print generated config instead of writing it")

    parser.add_argument(
        "--sax-data-root",
        "--acdc-dir",
        dest="sax_data_root",
        default=os.getenv("SORAT_SAX_DATA_ROOT", os.getenv("SORAT_ACDC_DIR", "")),
        help="SAX default dataset root (legacy alias: --acdc-dir)",
    )
    parser.add_argument(
        "--sax-data-split",
        "--acdc-dataset",
        dest="sax_data_split",
        default=os.getenv("SORAT_SAX_DATA_SPLIT", "testing"),
        help="SAX dataset split folder (legacy alias: --acdc-dataset)",
    )
    parser.add_argument(
        "--sax-samplesheet",
        "--acdc-samplesheet",
        dest="sax_samplesheet",
        default=os.getenv("SORAT_SAX_SAMPLESHEET", os.getenv("SORAT_ACDC_SAMPLESHEET", "")),
        help="Explicit SAX default samplesheet (legacy alias: --acdc-samplesheet)",
    )

    parser.add_argument(
        "--atrial-data-root",
        "--mbas-root",
        dest="atrial_data_root",
        default=os.getenv("SORAT_ATRIAL_DATA_ROOT", os.getenv("SORAT_MBAS_ROOT", "")),
        help="Atrial default dataset root (legacy alias: --mbas-root)",
    )
    parser.add_argument(
        "--atrial-samplesheet",
        "--mbas-samplesheet",
        dest="atrial_samplesheet",
        default=os.getenv("SORAT_ATRIAL_SAMPLESHEET", os.getenv("SORAT_MBAS_SAMPLESHEET", "")),
        help="Explicit atrial default samplesheet (legacy alias: --mbas-samplesheet)",
    )

    parser.add_argument("--slurm-account", default=os.getenv("SORAT_SLURM_ACCOUNT", ""))

    parser.add_argument("--singularity-cache-dir", default=os.getenv("SORAT_SINGULARITY_CACHEDIR", str(Path.home() / ".singularity_cache")))
    parser.add_argument("--preprocess-cache-dir", default="")
    parser.add_argument("--outdir", default="")

    parser.add_argument("--singularity-local-binds", default="")
    parser.add_argument("--singularity-slurm-binds", default="")

    return parser.parse_args()


def main() -> int:
    args = parse_args()
    repo_root = Path(__file__).resolve().parents[1]

    default_outdir = str(repo_root / "results")
    default_pre_cache = str(repo_root / ".cache" / "preprocess")
    default_local_binds = f"{repo_root / 'bin'}:/app/bin,{repo_root / 'nnformer'}:/app/nnformer"
    default_slurm_binds = f"/arc:/arc,/scratch:/scratch,{repo_root / 'bin'}:/app/bin,{repo_root / 'nnformer'}:/app/nnformer"

    values = {
        "sax_data_root": args.sax_data_root,
        "sax_data_split": args.sax_data_split,
        "sax_samplesheet": args.sax_samplesheet,
        "atrial_data_root": args.atrial_data_root,
        "atrial_samplesheet": args.atrial_samplesheet,
        "slurm_account": args.slurm_account,
        "singularity_cache_dir": args.singularity_cache_dir,
        "preprocess_cache_dir": args.preprocess_cache_dir or default_pre_cache,
        "outdir": args.outdir or default_outdir,
        "singularity_local_binds": args.singularity_local_binds or default_local_binds,
        "singularity_slurm_binds": args.singularity_slurm_binds or default_slurm_binds,
    }

    if not args.non_interactive:
        print("SORAT setup wizard")
        print("Press Enter to accept defaults. Leave optional values blank if unused.")
        print()

        values["sax_data_root"] = _prompt_value("SAX default dataset root (ACDC-style; contains testing/ or training/)", values["sax_data_root"])
        values["sax_data_split"] = _prompt_value("SAX dataset split", values["sax_data_split"] or "testing")
        values["sax_samplesheet"] = _prompt_value("SAX samplesheet path override (optional)", values["sax_samplesheet"])

        values["atrial_data_root"] = _prompt_value("Atrial dataset root (optional; nnUNet layout or MBAS-style)", values["atrial_data_root"])
        values["atrial_samplesheet"] = _prompt_value("Atrial samplesheet path override (optional)", values["atrial_samplesheet"])

        values["slurm_account"] = _prompt_value("SLURM account/allocation (required for -profile slurm)", values["slurm_account"])

        values["singularity_cache_dir"] = _prompt_value("Singularity/Apptainer cache directory", values["singularity_cache_dir"])
        values["preprocess_cache_dir"] = _prompt_value("Preprocess cache directory", values["preprocess_cache_dir"])
        values["outdir"] = _prompt_value("Default output directory", values["outdir"])

        values["singularity_local_binds"] = _prompt_value("Local profile bind list", values["singularity_local_binds"])
        values["singularity_slurm_binds"] = _prompt_value("SLURM profile bind list", values["singularity_slurm_binds"])

    values["sax_data_root"] = _validate_existing_path(values["sax_data_root"], "SAX default data root", expect_file=False, non_interactive=args.non_interactive)
    values["sax_samplesheet"] = _validate_existing_path(values["sax_samplesheet"], "SAX samplesheet", expect_file=True, non_interactive=args.non_interactive)
    values["atrial_data_root"] = _validate_existing_path(values["atrial_data_root"], "Atrial data root", expect_file=False, non_interactive=args.non_interactive)
    values["atrial_samplesheet"] = _validate_existing_path(values["atrial_samplesheet"], "Atrial samplesheet", expect_file=True, non_interactive=args.non_interactive)

    if not values["sax_data_root"] and not values["sax_samplesheet"]:
        message = "Neither SAX default dataset root nor SAX samplesheet is configured. SAX model runs without --input will fail."
        if args.non_interactive:
            print(f"Warning: {message}")
        else:
            print(f"Warning: {message}")
            if not _prompt_yes_no("Continue anyway?", default=True):
                print("Aborted.")
                return 1

    config_text = _build_config_text(values, repo_root)
    if args.print_only:
        print(config_text)
        return 0

    config_dir = repo_root / ".sorat"
    config_dir.mkdir(parents=True, exist_ok=True)
    config_path = config_dir / "user.config"

    if config_path.exists() and not args.force:
        print(f"Config already exists: {config_path}")
        print("Re-run with --force to overwrite.")
        return 1

    config_path.write_text(config_text, encoding="utf-8")

    print(f"Wrote per-user config: {config_path}")
    print()
    print("Next steps:")
    print("  nextflow run main.nf -c .sorat/user.config -profile local")
    print("  nextflow run main.nf -c .sorat/user.config -profile slurm")
    print()
    print("Tip: Re-run this wizard any time your paths or allocation change.")

    return 0


if __name__ == "__main__":
    sys.exit(main())
